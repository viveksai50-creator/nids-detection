"""Aggregate results/raw/*.json into tables, figures and statistics.

Usage:
    python -m src.aggregate             # tables + figures
    python -m src.aggregate --stats     # + Friedman/Nemenyi/Wilcoxon
    python -m src.aggregate --latex     # also write .tex tables
"""

from __future__ import annotations

import argparse
import json
import sys

import numpy as np
import pandas as pd

from src import config as C
from src.eval import stats as S

PRIMARY = f"{C.PRIMARY_FPR:g}"


def load_long() -> pd.DataFrame:
    rows = []
    for p in sorted(C.RAW_RESULTS_DIR.glob("*.json")):
        with open(p) as f:
            r = json.load(f)
        # Keep schema-only smoke fixtures out of research tables.  A final run
        # always has the complete runner provenance and a numeric seed.
        required = {"family", "model", "seed", "device", "train_seconds", "peak_rss_mb", "metrics"}
        if not required.issubset(r) or not isinstance(r["seed"], int):
            print(f"skip non-final result fixture: {p.name}", file=sys.stderr)
            continue
        m = r["metrics"]
        base = {
            "family": r["family"],
            "model": r["model"],
            "seed": r["seed"],
            "device": r["device"],
            "train_seconds": r["train_seconds"],
            "peak_rss_mb": r["peak_rss_mb"],
            "batch_us_per_row": r.get("latency", {}).get("batch_us_per_row", np.nan),
            "single_p50_ms": r.get("latency", {}).get("single_p50_ms", np.nan),
            "single_p95_ms": r.get("latency", {}).get("single_p95_ms", np.nan),
            "roc_auc": m["roc_auc"],
            "pr_auc": m["pr_auc"],
            "unseen_roc_auc": m["unseen_roc_auc"],
            "n_unseen": m["n_unseen"],
        }
        for q, mq in m["at_fpr"].items():
            for k in (
                "udr",
                "precision",
                "recall",
                "macro_f1",
                "mcc",
                "realised_fpr_benign_test",
                "known_attack_recall",
                "accuracy",
            ):
                base[f"{k}@{q}"] = mq[k]
            base[f"udr_ci_lo@{q}"], base[f"udr_ci_hi@{q}"] = mq["udr_ci95"]
        rows.append(base)
    if not rows:
        raise SystemExit(f"no results in {C.RAW_RESULTS_DIR}")
    return pd.DataFrame(rows)


def mean_std_matrix(df: pd.DataFrame, col: str) -> pd.DataFrame:
    g = df.groupby(["family", "model"])[col]
    mean, std = g.mean().unstack("model"), g.std().unstack("model")
    return mean.round(4).astype(str) + " ± " + std.round(4).fillna(0).astype(str)


def to_markdown(df: pd.DataFrame, title: str) -> str:
    cols = [str(c) for c in df.columns]
    lines = [f"### {title}", "", "| " + " | ".join([df.index.name or ""] + cols) + " |", "| " + " | ".join(["---"] * (len(cols) + 1))]
    for idx, row in df.iterrows():
        lines.append("| " + " | ".join([str(idx)] + [str(v) for v in row.values]) + " |")
    return "\n".join(lines) + "\n"


def write_tables(df: pd.DataFrame, latex: bool) -> None:
    C.ensure_dirs()
    md = []
    t1 = mean_std_matrix(df, f"udr@{PRIMARY}")
    t1.to_csv(C.TABLES_DIR / "t1_udr_by_family_model.csv")
    md.append(to_markdown(t1, f"T1 UDR @ FPR {PRIMARY}"))

    t2 = mean_std_matrix(df, "unseen_roc_auc")
    t2.to_csv(C.TABLES_DIR / "t2_unseen_auc_by_family_model.csv")
    md.append(to_markdown(t2, "T2 Unseen ROC-AUC"))

    overall_cols = [
        "pr_auc",
        "roc_auc",
        f"macro_f1@{PRIMARY}",
        f"mcc@{PRIMARY}",
        f"precision@{PRIMARY}",
        f"recall@{PRIMARY}",
        f"realised_fpr_benign_test@{PRIMARY}",
    ]
    t3 = df.groupby("model")[overall_cols].mean().round(4)
    t3.to_csv(C.TABLES_DIR / "t3_overall_by_model.csv")
    md.append(to_markdown(t3, "T3 Overall metrics"))

    t4 = df.groupby("model")[["train_seconds", "batch_us_per_row", "single_p50_ms", "single_p95_ms", "peak_rss_mb"]].median().round(3)
    t4.to_csv(C.TABLES_DIR / "t4_efficiency_by_model.csv")

    df["_ci_w"] = df[f"udr_ci_hi@{PRIMARY}"] - df[f"udr_ci_lo@{PRIMARY}"]
    t8 = df.groupby("family").agg(n_unseen=("n_unseen", "first"), mean_udr_ci_width=("_ci_w", "mean")).round(4)
    t8.to_csv(C.TABLES_DIR / "t8_family_sizes_ci.csv")
    md.append(to_markdown(t8, "T8 Unseen-family sizes and mean UDR CI width"))

    udr_fpr = df.melt(id_vars=["family", "model"], value_vars=[f"udr@{q}" for q in C.TARGET_FPRS], var_name="fpr", value_name="udr").groupby(["model", "fpr"])["udr"].mean().unstack("fpr").round(4)
    udr_fpr.to_csv(C.TABLES_DIR / "t7_udr_vs_fpr.csv")
    md.append(to_markdown(udr_fpr, "T7 Mean UDR vs target FPR"))

    with open(C.TABLES_DIR / "TABLES.md", "w") as f:
        f.write("# Result tables (generated by src/aggregate.py - do not edit by hand)\n\n" + "\n".join(md))

    if latex:
        for name, t in {"t1": t1, "t2": t2, "t3": t3, "t4": t4}.items():
            with open(C.TABLES_DIR / f"{name}.tex", "w") as f:
                f.write(t.to_latex())
    print("tables written to", C.TABLES_DIR)


def write_figures(df: pd.DataFrame) -> None:
    import matplotlib
    matplotlib.use("Agg")
    import matplotlib.pyplot as plt

    C.ensure_dirs()

    # F1 heatmap UDR
    mat = df.groupby(["family", "model"])[f"udr@{PRIMARY}"].mean().unstack("model")
    fig, ax = plt.subplots(figsize=(8, 5))
    im = ax.imshow(mat.to_numpy(), vmin=0, vmax=1, cmap="viridis")
    ax.set_xticks(range(mat.shape[1]))
    ax.set_xticklabels(mat.columns, rotation=45, ha="right")
    ax.set_yticks(range(mat.shape[0]))
    ax.set_yticklabels(mat.index)
    for i in range(mat.shape[0]):
        for j in range(mat.shape[1]):
            ax.text(j, i, f"{mat.iloc[i, j]:.2f}", ha="center", va="center", color="w", fontsize=8)
    fig.colorbar(im, ax=ax, label=f"UDR @ FPR {PRIMARY}")
    ax.set_title("Unseen Detection Rate by held-out family")
    fig.tight_layout()
    fig.savefig(C.FIGURES_DIR / "f1_udr_heatmap.png", dpi=200)
    plt.close(fig)

    # F6 UDR vs latency
    g = df.groupby("model").agg(udr=(f"udr@{PRIMARY}", "mean"), lat=("batch_us_per_row", "median"))
    fig, ax = plt.subplots(figsize=(6, 4))
    ax.scatter(g.lat, g.udr)
    for m, r in g.iterrows():
        ax.annotate(m, (r.lat, r.udr))
    ax.set_xscale("log")
    ax.set_xlabel("batch latency (us/flow, median)")
    ax.set_ylabel(f"mean UDR @ FPR {PRIMARY}")
    ax.set_title("Detection vs latency")
    fig.savefig(C.FIGURES_DIR / "f6_udr_vs_latency.png", dpi=200)
    plt.close(fig)

    # F7 UDR vs target FPR
    fig, ax = plt.subplots(figsize=(6, 4))
    for m, sub in df.groupby("model"):
        ax.plot(C.TARGET_FPRS, [sub[f"udr@{q}"].mean() for q in C.TARGET_FPRS], marker="o", label=m)
    ax.set_xscale("log")
    ax.set_xlabel("target FPR on benign validation")
    ax.set_ylabel("mean UDR")
    ax.legend()
    fig.tight_layout()
    fig.savefig(C.FIGURES_DIR / "f7_udr_vs_fpr.png", dpi=200)
    plt.close(fig)

    print("figures written to", C.FIGURES_DIR)


def write_stats(df: pd.DataFrame) -> None:
    C.ensure_dirs()
    long = df.rename(columns={f"udr@{PRIMARY}": "value"})[["family", "model", "seed", "value"]]
    out: dict = {"metric": f"udr@{PRIMARY}", "per_family": {}, "overall": {}}
    for fam, sub in long.groupby("family"):
        out["per_family"][fam] = {"friedman": S.friedman(sub, block="seed")}
        nem = S.nemenyi(sub, block="seed")
        if nem is not None:
            nem.to_csv(C.STATS_DIR / f"nemenyi_{fam}.csv")
    out["overall"]["friedman_families_as_blocks"] = S.friedman(long, block="family")
    nem = S.nemenyi(long, block="family")
    if nem is not None:
        nem.to_csv(C.STATS_DIR / "nemenyi_overall.csv")
    models = set(long.model.unique())
    ad = [m for m in ("iforest", "ocsvm", "ae", "vae") if m in models]
    sup = [m for m in ("rf", "xgb") if m in models]
    if "scarf" in models and (ad or sup):
        means = long.groupby("model").value.mean()
        baselines = []
        if ad:
            baselines.append(max(ad, key=lambda m: means[m]))
        if sup:
            baselines.append(max(sup, key=lambda m: means[m]))
        out["rq3_scarf_vs_best"] = S.targeted_comparisons(long, "scarf", baselines)
    with open(C.STATS_DIR / "stats.json", "w") as f:
        json.dump(out, f, indent=2, default=str)
    print(json.dumps(out, indent=2, default=str))


def main(argv=None) -> int:
    p = argparse.ArgumentParser()
    p.add_argument("--stats", action="store_true")
    p.add_argument("--latex", action="store_true")
    a = p.parse_args(argv)
    df = load_long()
    df.to_csv(C.TABLES_DIR / "all_runs_long.csv", index=False)
    write_tables(df, latex=a.latex)
    write_figures(df)
    if a.stats:
        write_stats(df)
    return 0


if __name__ == "__main__":
    sys.exit(main())
